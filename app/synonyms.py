def expand(query: str) -> list[str]:
    """返回要追加到检索词里的扩展词。"""
    q = query.lower()
    extra: list[str] = []
    for triggers, terms in EXPANSIONS:
        if any(t in q for t in triggers):
            extra.extend(terms)
    # 去重保序
    seen, out = set(), []
    for t in extra:
        if t not in seen:
            seen.add(t)
            out.append(t)
    return out
